def build():
    models = []
    for (line, max_t, length), (sections, mass, profile, deck, sensors) in RAW_MODELS.items():
        model_id = f"vesta-{line.lower()}-{max_t}-{length}"
        full_name = f"ВЕСТА-{line}-{max_t}-{length}"

        metrology = METROLOGY_BY_MAX[max_t]
        axle = AXLE_LOADS.get((line, max_t))

        data_incomplete = any(v is None for v in (sections, mass, profile, deck, sensors))

        model_entry = {
            "id": model_id,
            "full_name": full_name,
            "line": line,
            "max_load_t": max_t,
            "length_m": length,
            "width_m": 3,
            "sections": sections,
            "sensors_count": sensors,
            "mass_kg": mass,
            "beam_profile": profile,
            "deck_default_mm": deck,
            "min_load_t": metrology["min_load_t"],
            "verification_division_kg": metrology["verification_division_kg"],
            "n_intervals": metrology["n_intervals"],
            "axle_loads_t": {
                "single": axle[0] if axle else None,
                "double": axle[1] if axle else None,
                "triple": axle[2] if axle else None,
                "quad":   axle[3] if axle else None,
            },
            "data_incomplete": data_incomplete,
            "notes": "Данные по П отсутствуют в справочнике. "
                     "Требуется уточнение у производства." if data_incomplete else None
        }
        models.append(model_entry)

    # Сортировка: линейка → тоннаж → длина (для удобства ревью)
    line_order = {"С": 1, "СЛ": 2, "Ф": 3, "ФЛ": 4, "П": 5}
    models.sort(key=lambda m: (line_order[m["line"]], m["max_load_t"], m["length_m"]))

    result = {
        "_meta": {
            "version": "0.1",
            "generated_at": "2026-04-23",
            "source": [
                "03_knowledge_base/spravochnik_vesta_fixed.md (v10.2 от 15.04.2025)",
                "03_knowledge_base/opisanie_tipa_VESTA_fixed.md (приказ от 20.03.2025 №544)"
            ],
            "scope": {
                "lines": ["С", "СЛ", "Ф", "ФЛ", "П"],
                "lengths_m": [18, 20, 22, 24],
                "max_loads_t": {
                    "С":  [40, 60, 80, 100, 120],
                    "СЛ": [40, 60, 80],
                    "Ф":  [40, 60, 80, 100],
                    "ФЛ": [40, 60, 80],
                    "П":  [100]
                }
            },
            "notes": [
                "Все модели в scope MVP. Модификации вне scope (М1, М2, К, Б, СБ, "
                "ФБ, ПВП, ПВС, длины <18 м) не включены — будут добавлены на "
                "последующих фазах.",
                "Поля с null и data_incomplete=true требуют уточнения у "
                "производства (актуально для всей линейки П).",
                "Температурные диапазоны датчика и индикатора вынесены в "
                "equipment_defaults, т.к. одинаковы для всех моделей."
            ]
        },
        "equipment_defaults": DEFAULT_EQUIPMENT_TEMP,
        "line_defaults": LINE_DEFAULTS,
        "models": models
    }

    return result


if __name__ == "__main__":
    data = build()
    out_path = Path(__file__).parent / "models.json"
    out_path.write_text(
        json.dumps(data, ensure_ascii=False, indent=2),
        encoding="utf-8"
    )
    print(f"OK: сгенерировано {len(data['models'])} моделей -> {out_path}")
    # Короткая сводка для визуального контроля
    from collections import Counter
    by_line = Counter(m["line"] for m in data["models"])
    incomplete = sum(1 for m in data["models"] if m["data_incomplete"])
    print(f"По линейкам: {dict(by_line)}")
    print(f"С неполными данными (нужно уточнять у производства): {incomplete}")
